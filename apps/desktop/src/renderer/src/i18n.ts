const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, es };

export function resolveLocale(preferred: Locale | null, system: string): Locale {
  if (preferred) return preferred;
  return system.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  // "1 bot", not "1 bots": a key may have a singular form under "<key>.one".
  const one = vars?.n === 1 ? ((dictionaries[locale] as Record<string, string>)[`${key}.one`] ?? (en as Record<string, string>)[`${key}.one`]) : undefined;
  let s = one ?? dictionaries[locale][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return keys(s);
}
